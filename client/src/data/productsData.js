// Filter helper for local resilience
export function filterLocalProducts(items, category, benefit, search, juiceOnly) {
  return items.filter((p) => {
    if (category && p.category !== category) return false
    if (benefit && !p.healthBenefits?.includes(benefit)) return false
    if (juiceOnly && !p.isJuiceSuitable) return false
    if (search) {
      const q = search.toLowerCase()
      const matchName = p.name.toLowerCase().includes(q)
      const matchPlace = (p.place || '').toLowerCase().includes(q)
      const matchFarmer = (p.farmer?.name || '').toLowerCase().includes(q)
      if (!matchName && !matchPlace && !matchFarmer) return false
    }
    return true
  })
}
